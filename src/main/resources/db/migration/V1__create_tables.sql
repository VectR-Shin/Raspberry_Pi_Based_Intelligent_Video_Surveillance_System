CREATE TABLE device (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        user_id VARCHAR(50),
                        device_identifier VARCHAR(50) NOT NULL,
                        alias VARCHAR(20),
                        registered_at TIMESTAMP(6),

                        CONSTRAINT uq_device_device_identifier UNIQUE (device_identifier),
                        CONSTRAINT uq_device_user_alias UNIQUE(user_id, alias)
);

CREATE TABLE log (
                     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                     device_id BIGINT NOT NULL,
                     event_type VARCHAR(20) NOT NULL,
                     detected_at TIMESTAMP(6) NOT NULL,

                     CONSTRAINT fk_log_device FOREIGN KEY (device_id) REFERENCES device (id),

                     CONSTRAINT chk_log_event_type CHECK (event_type IN ('PERSON_DETECTED', 'CAMERA_OBSTRUCTED'))
);

CREATE TABLE image (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    log_id BIGINT NOT NULL,
    storage_path VARCHAR(500) NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    file_size BIGINT NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,

    CONSTRAINT uq_image_log_id UNIQUE (log_id),

    CONSTRAINT fk_image_log FOREIGN KEY (log_id) REFERENCES log (id)
);
